#!/usr/bin/env python3
"""Generate the coefficient tables of special.goose and print them.

Run (the venv with mpmath is not installed system wide):
  tmp/special/venv/bin/python test/make_special_coeffs.py > special_coeffs.txt

Paste the printed block into special.goose after the header. The package
holds the numbers only. The script holds no package algorithm.

Tables (mpmath at 60 to 140 digits):
  ERF_SERIES     a[n] = (-1)^n (2/sqrt(pi)) / (n! (2n+1))
  H1_CHEB H2_CHEB G_CHEB   Chebyshev fits of exp(x^2) erfc(x)
  ASYM_COEF      (2n-1)!! of the erfc tail series
  EXPM1_SERIES   1/(n+2)!
  LN2_HI LN2_LO  ln 2 split; k*LN2_HI is exact
  GAMMA_C        Chebyshev fit of gamma(x) on [1,2]
  LGAMMA_C       fit of lgamma(x)/((x-1)(x-2)) on [0.5,3]
  STIR_C         Stirling terms B2k/(2k(2k-1))
  X0_HI X0_LO    the root of the digamma, split exact
  DIG_C DIG2_C   fits of the digamma on [1,3] and [3,10]
  DIG_ASY        Stirling terms B2k/(2k)
  STIR_H STIR_L  Stirling terms as double double pairs
  LOG1PMX_H LOG1PMX_L    2/(j+2) as double double pairs
  LOGP_H LOGP_L          1/(2k+1) as double double pairs
  B_SAD          the saddle point series
  ERFCA          asymptotic scaled erfc
  HALF_LN2PI_H L LN2PI_H L     ln(2 pi)/2 and ln(2 pi) as pairs
  LG1P_H LG1P_L  the series of log gamma(1 + a) in a: -euler and (-1)^k zeta(k)/k
"""
import sys
from fractions import Fraction

import mpmath as mp


def cheb_coef(f, a, b, n):
    """Chebyshev interpolation coefficients of f on [a, b], n terms."""
    a = mp.mpf(a)
    b = mp.mpf(b)
    xs = [mp.cos(mp.pi * (k + mp.mpf(1) / 2) / n) for k in range(n)]
    fv = [f((b - a) / 2 * x + (a + b) / 2) for x in xs]
    c = []
    for j in range(n):
        s = sum(fv[k] * mp.cos(mp.pi * j * (k + mp.mpf(1) / 2) / n) for k in range(n))
        c.append(2 * s / n)
    c[0] /= 2
    return c


def bern(n):
    """The Bernoulli numbers B0..Bn."""
    a = [Fraction(0)] * (n + 1)
    out = []
    for m in range(n + 1):
        a[m] = Fraction(1, m + 1)
        for j in range(m, 0, -1):
            a[j - 1] = j * (a[j - 1] - a[j])
        out.append(a[0])
    return out


BN = bern(24)


def table(name, vals, per=3):
    out = ["const %s: f64[%d] = [" % (name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + " ".join(repr(float(v)) + "," for v in vals[i:i + per]))
    out.append("];")
    return "\n".join(out)


def pairs(hp, lp, name):
    out = ["const %s_H: f64[%d] = [" % (name, len(hp)),
           "    " + " ".join(repr(float(v)) + "," for v in hp),
           "];",
           "const %s_L: f64[%d] = [" % (name, len(lp)),
           "    " + " ".join(repr(float(v)) + "," for v in lp),
           "];"]
    return "\n".join(out)


def dd_split(v):
    """One value as a double double pair."""
    v = mp.mpf(v)
    hi = float(v)
    return hi, float(v - mp.mpf(hi))


def consts(items):
    out = []
    for name, v in items:
        out.append("const %s: f64 = %s;" % (name, repr(float(v))))
    return "\n".join(out)


def main():
    lines = []
    lines.append("// Generated by test/make_special_coeffs.py. Do not edit by hand.")

    # ---- erf family and the accurate log and exponential, 60 digits ----
    mp.mp.dps = 60
    pi = mp.pi
    sq2pi = mp.sqrt(pi)
    erf_n = 18
    lines.append(table("ERF_SERIES",
                       [(-1) ** n * 2 / sq2pi / (mp.factorial(n) * (2 * n + 1)) for n in range(erf_n)]))
    h1 = cheb_coef(lambda x: mp.exp(x * x) * mp.erfc(x), mp.mpf("0.5"), mp.mpf("1.5"), 21)
    h2 = cheb_coef(lambda x: mp.exp(x * x) * mp.erfc(x), mp.mpf("1.5"), mp.mpf("3.0"), 21)
    g3 = cheb_coef(lambda x: sq2pi * x * mp.exp(x * x) * mp.erfc(x), mp.mpf("3.0"), mp.mpf("7.0"), 25)
    lines.append(table("H1_CHEB", h1))
    lines.append(table("H2_CHEB", h2))
    lines.append(table("G_CHEB", g3))
    asym, v = [], mp.mpf(1)
    for n in range(27):
        if n:
            v *= 2 * n - 1
        asym.append(v)
    lines.append(table("ASYM_COEF", asym))
    lines.append(table("EXPM1_SERIES", [1 / mp.factorial(n + 2) for n in range(18)]))
    ln2 = mp.log(2)
    hi = mp.mpf(float(mp.nint(ln2 * 2 ** 32) / 2 ** 32))
    dd_hi, dd_lo = dd_split(ln2)
    lines.append(consts([("DD_LN2_HI", dd_hi), ("DD_LN2_LO", dd_lo)]))
    lines.append(consts([("LN2_HI", hi), ("LN2_LO", ln2 - hi), ("INV_LN2", 1 / ln2),
                         ("SQRT_PI", sq2pi), ("INV_SQRT_PI", 1 / sq2pi),
                         ("HALF_SQRT_PI", sq2pi / 2), ("TWO_OVER_SQRT_PI", 2 / sq2pi),
                         ("PI", pi), ("PI_OVER_12", pi / 12)]))

    # ---- gamma, log gamma and digamma, 60 digits ----
    gc = cheb_coef(lambda x: mp.gamma(x), mp.mpf(1), mp.mpf(2), 24)
    lines.append(table("GAMMA_C", gc))
    lgc = cheb_coef(lambda x: mp.loggamma(x) / ((x - 1) * (x - 2)), mp.mpf("0.5"), mp.mpf(3), 40)
    lines.append(table("LGAMMA_C", lgc))
    lines.append(table("STIR_C", [BN[2 * k] / (2 * k * (2 * k - 1)) for k in range(1, 10)]))
    x0 = mp.findroot(mp.digamma, mp.mpf("1.46"))
    x0h, x0l = dd_split(x0)
    lines.append(consts([("X0_HI", x0h), ("X0_LO", x0l)]))
    def dg_fit(x):
        x = mp.mpf(x)
        return mp.polygamma(1, x0) if abs(x - x0) < mp.mpf("1e-40") else mp.digamma(x) / (x - x0)
    dc = cheb_coef(dg_fit, mp.mpf(1), mp.mpf(3), 40)
    lines.append(table("DIG_C", dc))
    dc2 = cheb_coef(lambda x: mp.digamma(x), mp.mpf(3), mp.mpf(10), 36)
    lines.append(table("DIG2_C", dc2))
    lines.append(table("DIG_ASY", [BN[2 * k] / (2 * k) for k in range(1, 10)]))

    # ---- the layer of the incomplete functions, 140 digits ----
    mp.mp.dps = 140
    stir = [mp.bernoulli(2 * k) / (2 * k * (2 * k - 1)) for k in range(1, 15)]
    sh, sl = zip(*[dd_split(v) for v in stir])
    lines.append(pairs(sh, sl, "STIR"))
    lm = [(-mp.mpf(1)) ** j * mp.mpf(2) / (j + 2) for j in range(80)]
    mh, ml = zip(*[dd_split(v) for v in lm])
    lines.append(pairs(mh, ml, "LOG1PMX"))
    lgc2 = [mp.mpf(1) / (2 * k + 1) for k in range(26)]
    ch, cl = zip(*[dd_split(v) for v in lgc2])
    lines.append(pairs(ch, cl, "LOGP"))
    # the saddle series by Cauchy integrals of 1/v(t)
    nb = 41
    r = mp.mpf("0.09")
    npts = 256
    def v_at(t):
        u = mp.sqrt(2) * t
        for _ in range(60):
            f = u - mp.log1p(u) - t * t
            fp = u / (1 + u)
            du = f / fp
            u -= du
            if abs(du) < mp.mpf(10) ** -120:
                break
        return u / t
    b = []
    for n in range(nb):
        s = mp.mpf(0)
        for i in range(npts):
            th = 2 * mp.pi * i / npts
            t = r * mp.e ** (1j * th)
            s += (1 / v_at(t)) / t ** n
        b.append(mp.re(s / npts))
    lines.append(table("B_SAD", b))
    ea = [mp.mpf(1)]
    for k in range(1, 13):
        ea.append(-(2 * k - 1) * ea[-1])
    lines.append(table("ERFCA", ea))
    for name, val in (("HALF_LN2PI", mp.log(2 * mp.pi) / 2), ("LN2PI", mp.log(2 * mp.pi))):
        h_, l_ = dd_split(val)
        lines.append(consts([(name + "_H", h_), (name + "_L", l_)]))

    # the series of ln Gamma(1 + a) for a below 1e-3, as pairs
    lg = [-mp.euler] + [(-1) ** k * mp.zeta(k) / k for k in range(2, 14)]
    gh, gl = zip(*[dd_split(v) for v in lg])
    lines.append(pairs(gh, gl, "LG1P"))

    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
