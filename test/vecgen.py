"""Shared writer of the generated vector files.

Used by test/make_family_vectors.py, test/make_association_vectors.py and
test/make_distance_vectors.py. Each file holds one function
run_<group>_vectors() with one check per measured row. Needs Python 3.
"""
import math


def f(v):
    v = float(v)
    if math.isnan(v):
        return "(0.0 / 0.0)"
    if math.isinf(v):
        return "(1.0 / 0.0)" if v > 0 else "(-1.0 / 0.0)"
    return repr(v)


def arr(v):
    return "[" + ", ".join(f(x) for x in v) + "]"


class G:
    """One output file."""

    def __init__(self, name, script, tol="1e-12"):
        self.name = name
        self.script = script
        self.tol = tol
        self.lines = []
        self.n = 0

    def decl(self, nm, v):
        self.lines.append(f"    let {nm}: f64[{len(v)}] = {arr(v)};")

    def decl_i(self, nm, v):
        self.lines.append(f"    let {nm}: i64[{len(v)}] = [" + ", ".join(str(int(x)) for x in v) + "];")

    def field(self, label, call, fields, tol=None):
        """call returns a struct and a code; fields maps a field name to its value."""
        self.n += 1
        k = self.n
        self.lines.append(f"    let r{k}, c{k} = {call};")
        for name, want in fields.items():
            self.lines.append(f'    chk_val(bad, "{label} {name}", r{k}.{name}, c{k}, {f(want)}, {tol or self.tol});')

    def val(self, label, call, want, tol=None):
        self.n += 1
        k = self.n
        self.lines.append(f"    let v{k}, c{k} = {call};")
        self.lines.append(f'    chk_val(bad, "{label}", v{k}, c{k}, {f(want)}, {tol or self.tol});')

    def val2(self, label, call, want, tol=None):
        """call returns two values and a code; both are checked."""
        self.n += 1
        k = self.n
        self.lines.append(f"    let a{k}, b{k}, c{k} = {call};")
        self.lines.append(f'    chk_val(bad, "{label} first", a{k}, c{k}, {f(want[0])}, {tol or self.tol});')
        self.lines.append(f'    chk_val(bad, "{label} second", b{k}, c{k}, {f(want[1])}, {tol or self.tol});')

    def lst(self, label, call, want, tol=None, name="out"):
        """call fills the list `name`; its last result is the code."""
        self.n += 1
        k = self.n
        self.lines.append(f"    let _r{k}, c{k} = {call};")
        self.lines.append(f"    let w{k}: f64[{len(want)}] = {arr(want)};")
        self.lines.append(f'    chk_list(bad, "{label}", {name}[..], c{k}, w{k}[..], {tol or self.tol});')

    def fill(self, label, call, want, tol=None, name="out"):
        """call fills the list `name` and returns only a code."""
        self.n += 1
        k = self.n
        self.lines.append(f"    let c{k} = {call};")
        self.lines.append(f"    let w{k}: f64[{len(want)}] = {arr(want)};")
        self.lines.append(f'    chk_list(bad, "{label}", {name}[..], c{k}, w{k}[..], {tol or self.tol});')

    def code(self, label, call, want):
        self.n += 1
        k = self.n
        self.lines.append(f"    let _v{k}, c{k} = {call};")
        self.lines.append(f'    chk_code(bad, "{label}", c{k}, {want});')

    def code3(self, label, call, want):
        """call returns two values and a code; only the code is checked."""
        self.n += 1
        k = self.n
        self.lines.append(f"    let _a{k}, _b{k}, c{k} = {call};")
        self.lines.append(f'    chk_code(bad, "{label}", c{k}, {want});')

    def codeonly(self, label, call, want):
        """call returns only a code."""
        self.n += 1
        k = self.n
        self.lines.append(f"    let c{k} = {call};")
        self.lines.append(f'    chk_code(bad, "{label}", c{k}, {want});')

    def raw(self, text):
        self.lines.append("    " + text)

    def write(self, extra_vars=""):
        head = (f"// Generated by test/{self.script}. Do not edit by hand.\n"
                f"// The measured rows of the {self.name} calls: the answers of SciPy 1.18.1.\n"
                "namespace suite;\n\nimport std;\nimport math;\nimport statistics from \"../..\";\n\n"
                f"fn run_{self.name}_vectors() -> i64 {{\n    var bad: i64 = 0;\n"
                "    var out: f64[>..] = [];\n    var out2: f64[>..] = [];\n" + extra_vars)
        body = "\n".join(self.lines)
        open(f"test/suite/{self.name}_vectors.goose", "w").write(head + body + "\n    return bad;\n}\n")
